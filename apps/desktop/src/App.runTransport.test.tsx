const mode = (name: string) =>
  screen.getByRole("radio", { name }).getAttribute("aria-checked");

/**
 * Operate the contact at the origin the way a reader does.
 *
 * Deliberately NOT `useSchematic.actuateContact`: the store call moves the part
 * but never reaches `Canvas`'s `onActuate`, and it is that callback which tells
 * App the change was an actuation rather than an edit. A test that skipped it
 * would exercise the edit branch and prove nothing about the live path.
 */
async function throwContactOnCanvas() {
  await waitFor(() => expect(document.querySelector("svg.canvas")).toBeTruthy());
  const svg = document.querySelector("svg.canvas")!;
  fireEvent.pointerDown(svg, { button: 0, clientX: 0, clientY: 0 });
  fireEvent.pointerUp(svg, { button: 0, clientX: 0, clientY: 0 });
}

