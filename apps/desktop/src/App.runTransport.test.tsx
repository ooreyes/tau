/**
 * The engine bridge, replaced at its seam rather than at Tauri's.
 *
 * jsdom has no `invoke`, so the real bridge answers `not-available` for
 * everything and a live run could never start — which would make every
 * assertion below about the *absence* of a feature. Only `startLiveSession` is
 * substituted; the frame plumbing, the poll cadence and the stop-reason mapping
 * are covered by `nativeLive`'s own suite and are not re-implemented here.
 *
 * The fake echoes the requested vector names back as the latched ones, because
 * that is the contract the real child keeps and the hook filters against it:
 * net ids are generated by `extractCircuit` and are not knowable from a test.
 */
const halt = vi.fn(async () => ({ kind: "ended" as const, ended: endedByUser() }));
const alter = vi.fn(async (_options: { instance: string; value: string }) => ({
  ok: true as const,
  value: { ...endedByUser().telemetry, running: true, stopReason: null },
}));
let onEndHook: ((outcome: { kind: "ended"; ended: ReturnType<typeof endedByUser> }) => void) | null = null;

/**
 * A run that ended of its own accord, so `resolveStopReason` keeps the ENGINE's
 * reason instead of taking Tau's intent. Used to give a finished live session a
 * stop reason no bounded run could ever produce, which is the only way to tell
 * "the transport is describing this run" from "the transport is still holding
 * the last one's sentence" apart.
 */
function endedByDivergence() {
  const base = endedByUser();
  return {
    ...base,
    engineReason: "diverged" as const,
    reason: { kind: "diverged" as const, atCircuitTime: 1e-4, detail: "timestep too small" },
    detail: "timestep too small",
    telemetry: { ...base.telemetry, stopReason: "diverged" as const },
  };
}

function endedByUser() {
  const telemetry = {
    running: false,
    wallSeconds: 0.2,
    solvedSamples: 0,
    vectorCount: 2,
    scalars: 0,
    scalarBudget: 1_000_000,
    pointsPerSecond: 0,
    deliveredSamples: 0,
    decimatedSamples: 0,
    stride: 1,
    stopReason: "halted-by-user" as const,
    stopDetail: "The live run was halted.",
    engineLog: [],
  };
  return {
    engineReason: "halted-by-user" as const,
    reason: { kind: "user-stopped" as const },
    detail: telemetry.stopDetail,
    telemetry,
    retention: { deliveredSamples: 0, decimatedSamples: 0, stride: 1, skew: 0, isWholeRun: true },
    solvedCircuitTime: 0,
  };
}

